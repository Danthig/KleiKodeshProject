/** `TimeZone.rawOffset`: like Kotlin's `map[id]!!`, an id missing from the snapshot throws. */
export function rawOffsetMilliseconds(timeZoneId: string): number {
  const rawOffset = RAW_OFFSET_MILLISECONDS_BY_TIME_ZONE_ID.get(timeZoneId)
  if (rawOffset === undefined) throw new Error(`No raw offset known for time zone '${timeZoneId}'`)
  return rawOffset
}
